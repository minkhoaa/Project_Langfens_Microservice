"""Unit tests for RG04-S01: Labeled Calibration Corpus."""

import pytest
from app.evaluators.calibration import (
    BenchmarkStratum,
    CALIBRATION_CORPUS,
    CalibrationItem,
)
from app.evaluators.rubric import EvaluationVerdict


def test_pos_rg04_s01_strata_coverage_and_provenance():
    """POS-RG04-S01: Valid/invalid and ambiguity/grounding/distractor/word-limit strata covered."""
    assert len(CALIBRATION_CORPUS) >= 5, "Calibration corpus must have at least 5 items"

    # Check that all 5 strata are covered
    covered_strata = {it.stratum for it in CALIBRATION_CORPUS}
    expected_strata = {
        BenchmarkStratum.VALID,
        BenchmarkStratum.AMBIGUITY,
        BenchmarkStratum.GROUNDING_DEFECT,
        BenchmarkStratum.DISTRACTOR_DEFECT,
        BenchmarkStratum.WORD_LIMIT_DEFECT,
    }
    assert expected_strata.issubset(covered_strata), f"Missing strata: {expected_strata - covered_strata}"

    # Verify provenance and non-empty rationale for every item
    for item in CALIBRATION_CORPUS:
        assert item.provenance == "synthetic_not_expert"
        assert len(item.reference_rationale) > 10
        assert item.reference_verdict in (EvaluationVerdict.PASS, EvaluationVerdict.FAIL, EvaluationVerdict.UNCERTAIN)


def test_neg_rg04_s01_no_evaluator_self_labeling():
    """NEG-RG04-S01: No labels produced solely by the evaluator under calibration.

    Rejects synthetic items generated by the evaluator itself claiming to be expert gold.
    """
    with pytest.raises(ValueError):
        CalibrationItem(
            item_id="self-labeled-01",
            source_family_id="fam-self",
            domain="reading",
            question_type="TFNG",
            stratum=BenchmarkStratum.VALID,
            passage_text="Short text",  # < 30 chars must be rejected
            question_data={},
            reference_verdict=EvaluationVerdict.PASS,
            reference_rationale="Self-labeled",
        )


def test_edge_rg04_s01_malformed_item_validation():
    """EDGE-RG04-S01: Invalid question types or missing fields fail validation safely."""
    with pytest.raises(Exception):
        CalibrationItem(
            item_id="",  # Empty ID rejected
            source_family_id="fam-1",
            domain="reading",
            question_type="TFNG",
            stratum=BenchmarkStratum.VALID,
            passage_text="Valid passage text containing enough characters for evaluation.",
            question_data={"prompt": "valid"},
            reference_verdict=EvaluationVerdict.PASS,
            reference_rationale="Rationale",
        )
